/** Synthetic interaction acceptance. Run under the site's heavy-run lease + nice. */
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const baseURL = process.env.COUNCIL_BASE_URL || 'http://localhost:3457';
const browser = await chromium.launch({channel:'chrome'});
const report = { checkedAt:new Date().toISOString(), checks:[], errors:[] };
const check = (name) => report.checks.push(name);
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  page.on('pageerror', error => report.errors.push(String(error)));
  page.on('console', message => {if(message.type()==='error') report.errors.push(message.text());});
  const open = async (path='/design-council-preview?page=people') => {await page.goto(baseURL+path);await page.getByRole('heading',{name:'People',exact:true}).waitFor();};
  await open();
  const names = () => page.locator('tbody th[scope=row] a > span:first-child').allTextContents();
  await page.getByRole('table').waitFor();
  assert.equal((await names()).length,4);check('Table keeps all four identities and all six evidence/date columns');
  assert.equal(await page.locator('td[data-label="Documents"]').count(),4);
  await page.getByLabel('Sort loaded records').selectOption('sources');
  assert.equal((await names())[0],'Arthur Bell');
  await page.getByRole('button',{name:'Reverse sort direction'}).click();
  assert.equal((await names())[0],'Samuel Finch');check('Numeric sort and direction change actual order');
  await page.getByLabel('Group records').selectOption('state');
  assert.equal(await page.locator('th[scope=rowgroup]').count(),4);assert.equal(await page.locator('table thead').count(),1);assert.equal((await names()).length,4);check('Grouping retains every record under one aligned table head');
  await page.getByRole('button',{name:'grid',exact:true}).click();
  await page.getByRole('table').waitFor({state:'hidden'});
  assert.equal(await page.locator('a[href^="/app/people/synthetic-"]:visible').count(),4);
  await page.getByRole('button',{name:'list',exact:true}).click();
  assert.equal(await page.locator('a[href^="/app/people/synthetic-"]:visible').count(),4);check('Grid and List retain every record link and all chosen fields');
  await page.getByRole('button',{name:'table',exact:true}).click();
  await page.locator('summary').filter({hasText:'View & columns'}).click();
  await page.getByRole('checkbox',{name:'Documents',exact:true}).uncheck();
  assert.equal(await page.locator('td[data-label="Documents"]').count(),0);
  await page.getByRole('button',{name:'Show all columns'}).click();
  assert.equal(await page.locator('td[data-label="Documents"]').count(),4);check('Columns can be hidden explicitly and restored');
  await page.locator('summary').filter({hasText:'View & columns'}).click();
  await page.getByRole('checkbox',{name:'Select Eleanor Finch',exact:true}).check();
  await page.getByRole('button',{name:'Show selected',exact:true}).click();
  assert.equal((await names()).length,1);
  await page.getByRole('button',{name:'Show all loaded',exact:true}).click();
  assert.equal((await names()).length,4);
  await page.getByRole('button',{name:'Clear selection',exact:true}).click();check('Bulk selection changes the visible subset without losing records');
  await page.getByRole('button',{name:'+ New view',exact:true}).click();
  await page.getByLabel('View name').fill('Source comparison');
  await page.getByRole('button',{name:'Save view',exact:true}).click();
  await page.getByRole('button',{name:'Source comparison',exact:true}).waitFor();
  await page.getByLabel('Group records').selectOption('living');
  await page.getByRole('button',{name:'Source comparison · edited',exact:true}).waitFor();
  await page.getByRole('button',{name:'Discard changes',exact:true}).click();
  assert.equal(await page.getByLabel('Group records').inputValue(),'state');
  await page.reload();
  await page.getByRole('button',{name:'Source comparison',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Group records').inputValue(),'state');check('Named view, edited indicator, discard and reload persistence work');
  await open('/design-council-preview?page=people&fixtureOwner=other');
  assert.equal(await page.getByRole('button',{name:'Source comparison',exact:true}).count(),0);
  assert.equal(await page.getByLabel('Group records').inputValue(),'');
  await open();await page.getByRole('button',{name:'Source comparison',exact:true}).waitFor();check('Saved views are isolated between two fixture account preference keys');
  const raw = await page.evaluate(()=>localStorage.getItem('awf.collection.people.design-fixture'));
  assert.ok(raw.includes('Source comparison'));
  assert.ok(!raw.includes('synthetic-0')&&!raw.includes('Eleanor Finch'));check('Preferences do not copy records or selection IDs');
  await page.getByRole('button',{name:'Manage views',exact:true}).click();
  await page.getByRole('button',{name:'Remove view',exact:true}).click();
  await page.getByText('No saved views yet.',{exact:false}).waitFor();
  await page.keyboard.press('Escape');check('Removing a named view leaves all records intact');
  assert.equal((await names()).length,4);
  await open('/design-council-preview?page=people-more');
  assert.equal(await page.getByRole('link',{name:'Load more people',exact:true}).getAttribute('href'),'/app/people?page=2');check('Bounded result retains its next-page destination');
  await context.close();

  const phone = await browser.newContext({viewport:{width:320,height:844},isMobile:true,hasTouch:true});
  const mobile = await phone.newPage();
  mobile.on('pageerror',error=>report.errors.push(String(error)));
  await mobile.goto(baseURL+'/design-council-preview?page=people');
  await mobile.getByRole('heading',{name:'People',exact:true}).waitFor();
  assert.equal(await mobile.locator('li[data-row]:visible').count(),4);
  const firstCompact=mobile.locator('li[data-row]:visible').first();
  assert.ok((await firstCompact.innerText()).includes('docs'));
  assert.ok((await firstCompact.boundingBox()).height<240);check('Default phone List retains evidence fields in a compact recognition row');
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));check('320px table becomes labelled records without page overflow');
  await mobile.locator('summary').filter({hasText:'Group'}).click();
  await mobile.getByRole('radio',{name:'Research state',exact:true}).check();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.getByRole('button',{name:'Close group choices',exact:true}).click();
  await mobile.locator('summary').filter({hasText:'Sort'}).click();
  await mobile.getByRole('radio',{name:'Sources',exact:true}).check();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.getByRole('button',{name:'Close sort choices',exact:true}).click();check('Phone Group and Sort sheets keep all choices within 320px');
  await mobile.locator('summary').filter({hasText:'View & columns'}).click();
  await mobile.getByRole('radio',{name:'grid',exact:true}).check();
  await mobile.getByRole('button',{name:'Close options',exact:true}).click();
  assert.equal(await mobile.locator('a[href^="/app/people/synthetic-"]:visible').count(),4);
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));check('Phone View & columns exposes full view controls and Grid stays within 320px');
  await mobile.locator('summary').filter({hasText:'View & columns'}).click();
  await mobile.getByRole('radio',{name:'table',exact:true}).check();
  await mobile.getByRole('button',{name:'Close options',exact:true}).click();
  await mobile.goto(baseURL+'/design-council-preview?page=people-long');
  await mobile.getByRole('heading',{name:'People',exact:true}).waitFor();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));check('Unbroken long record name wraps at 320px without hiding text');
  await phone.close();

  const limited = await browser.newContext({viewport:{width:1440,height:1000}});
  await limited.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Storage disabled','SecurityError');};});
  const fallback = await limited.newPage();await fallback.goto(baseURL+'/design-council-preview?page=people');
  await fallback.getByRole('button',{name:'grid',exact:true}).click();
  await fallback.getByRole('table').waitFor({state:'hidden'});
  assert.equal(await fallback.locator('a[href^="/app/people/synthetic-"]:visible').count(),4);check('Presentation still works when browser storage is blocked');
  await limited.close();
  const international=await browser.newContext({viewport:{width:1280,height:900},locale:'fr-FR',timezoneId:'Pacific/Auckland'});
  const internationalPage=await international.newPage();
  internationalPage.on('pageerror',error=>report.errors.push(String(error)));
  internationalPage.on('console',message=>{if(message.type()==='error')report.errors.push(message.text());});
  await internationalPage.goto(baseURL+'/design-council-preview?page=people');
  await internationalPage.getByRole('heading',{name:'People',exact:true}).waitFor();
  assert.equal(await internationalPage.locator('time[datetime="2026-11-04T16:00:00.000Z"]:visible').count(),4);check('Client-rendered import dates keep explicit UTC meaning across locale/timezone without hydration errors');
  await international.close();
  assert.deepEqual(report.errors,[]);
} finally {
  await browser.close();
  writeFileSync(new URL('./collection-acceptance.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
}
console.log(`${report.checks.length} collection interaction checks passed.`);
